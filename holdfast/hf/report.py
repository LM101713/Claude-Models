"""Markdown validation report from the results dictionary."""

import math

from .params import P


def f(x, n=2):
    if x is None:
        return "-"
    if isinstance(x, float) and math.isinf(x):
        return "free"
    return f"{x:.{n}f}"


def write_report(r, path):
    L = []
    w = L.append
    w("# HF-04 HOLDFAST: CAD validation report\n")
    w("Generated by `holdfast.py`. **CAD validation only.** Every number below comes from exact "
      "solid geometry (manifold3d booleans, minimum-gap queries, ray casts) or from hand-calculation "
      "models. **Nothing has been printed or physically tested.** See `PHYSICAL_TESTING.md`.\n")
    ok = sum(c["ok"] for c in r["checks"])
    w(f"## 1. Verdicts: {ok} / {len(r['checks'])} pass\n")
    w("| | Check | Detail |\n|---|---|---|")
    for c in r["checks"]:
        w(f"| {'PASS' if c['ok'] else '**FAIL**'} | {c['check']} | {c['detail']} |")
    w("")

    w("## 2. Parts\n")
    w("| Part | Volume (cm³) | Shells | Genus | Print height (mm) | Bed contact (mm²) | Min wall, ray cast (mm) | Faces < 1.2 mm |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|")
    for p in r["parts"].values():
        t = p["thickness"]
        w(f"| {p['name']} | {p['volume_mm3'] / 1000:.2f} | {p['shells']} | {p['genus']} | {p['print_height']:.1f} | "
          f"{p['bed_area_mm2']:.0f} | {f(t['min'])} (1st pct {f(t['p01'])}) | {t['below_1p2']} of {t['samples']} |")
    w("\nGenus 2 on the base = the two screw holes. Thin-wall samples come from chamfer edges and the "
      "engraved text, where a ray grazes an edge. The thinnest structural features are the slot "
      "lips (1.6 mm, by design; they only resist pull-out) and the 2.2 mm floor under the undercut.\n")

    w("## 3. Wedge kinematics\n")
    s = r["summary"]
    w(f"Ramp angle {P.DELTA_DEG:.0f}° from vertical → friction needed at each contact "
      f"**tan({P.DELTA_DEG / 2:.0f}°) = {s['mu_required']:.3f}**. Roller travel {s['travel_total']:.1f} mm along the "
      f"ramp ({s['travel_vertical']:.1f} mm vertical) from the bottom stop (16 mm gap) to the keyhole (35 mm gap).\n")
    w("| Handle Ø (mm) | Travel s (mm) | Roller centre x, z (mm) | Grip height z (mm) | Roller turn (°) | To bottom stop (mm) | To keyhole (mm) |")
    w("|---:|---:|---|---:|---:|---:|---:|")
    for k in r["kinematics"]:
        w(f"| {k['handle_d']:.0f} | {k['travel_s']:.2f} | {k['roller_centre_x']:.2f}, {k['roller_centre_z']:.2f} | "
          f"{k['grip_height_z']:.2f} | {k['roller_turn_deg']:.0f} | {k['margin_to_bottom_stop']:.2f} | {k['margin_to_top_stop']:.2f} |")
    w("")

    w("## 4. Travel sweep (roller on its ramp, every position, both sides)\n")
    for key, label in (("sweep", "Standard roller"), ("sweep_grip", "Grip roller")):
        sw = r[key]
        w(f"**{label}:** {len(sw)} positions per side.\n")
        w("| Gap (mm) | min | max | Design |\n|---|---:|---:|---|")
        for col, des in (("overlap", "0 (mm³)"), ("gap_ramp", "0.02 (placed off the ramp; it is the rolling contact)"),
                         ("gap_walls", "1.0 pocket clearance"), ("gap_back", "0.30 axial"),
                         ("gap_stub", "> 0 between stops; 0.35 normal gap cone-to-lip")):
            vals = [x[f"L_{col}"] for x in sw] + [x[f"R_{col}"] for x in sw]
            w(f"| {col} | {min(vals):.3f} | {max(vals):.3f} | {des} |")
        w("")

    w("## 5. Retention and assembly\n")
    w("Pull-out test: from each travel position the roller is pulled straight out of the wall (+Y) until "
      "it first touches the base.\n")
    w("| Travel s (mm) | Equivalent handle Ø (mm) | Forward play before it is stopped (mm) |\n|---:|---:|---:|")
    for x in r["retention"]:
        w(f"| {x['s']:.2f} | {x['handle_d']:.1f} | {f(x['forward_play'])} |")
    a = r["assembly"]
    w(f"\nAssembly path (left roller): stub aligned with the keyhole 40 mm in front of the base, moved straight "
      f"in ({a['steps_insert']} poses), then rolled down the full ramp ({a['steps_roll']} poses): "
      f"**{len(a['hits'])} collisions**; closest stub approach while entering {a['min_stub_gap_insert']:.2f} mm. "
      f"Right roller: {len(r['assembly_right']['hits'])} collisions.\n")

    w("## 6. Handles\n")
    w("Each handle is placed 0.02 mm off the back plate, with both rollers 0.02 mm off it and off their ramps.\n")
    w("| Ø (mm) | Rated | Overlaps (handle/base, handle/rollers, rollers/base) | Gap to housings (mm) | Grip height (mm) | Contact y (mm) | Front margin on rim flat (mm) | Roller turn (°) |")
    w("|---:|:---:|---|---:|---:|---:|---:|---:|")
    for h in r["handles"]:
        w(f"| {h['handle_d']:.0f} | {'yes' if h['rated'] else 'no'} | {h['handle_base_overlap']:.3f}, "
          f"{h['handle_roller_overlap']:.3f}, {h['roller_base_overlap']:.3f} | {h['gap_handle_to_housings']:.2f} | "
          f"{h['grip_height_z']:.1f} | {h['contact_y']:.1f} | {h['contact_margin_front']:.2f} | {h['roller_turn_deg']:.0f} |")
    w("\nInsertion from the front (handle swept in from 60 mm out): "
      + "; ".join(f"Ø{i['handle_d']:.0f}: {'COLLIDES' if i['collides'] else 'clear'}, closest {i['min_gap_to_housings']:.1f} mm"
                  for i in r["insertion"]) + "\n")

    w("## 7. Printer-variation corners\n")
    w("The slot, keyhole and stub are rebuilt with each corner's dimensional errors and the fit, travel, "
      "assembly path and retention checks are run again. Holes shrink and bosses grow on most FDM printers.\n")
    w("| Corner | Roller | Assembly collisions | Travel collisions | Min stub gap (mm) | Forward play at s = 0 / 15 / 31 (mm) | Head over lip (mm) |")
    w("|---|---|---:|---:|---:|---|---:|")
    for c in r["corners"]:
        fp = " / ".join(f(x) for x in c["forward_play"])
        w(f"| {c['corner']} | {c['roller']} | {c['assembly_hits']} | {c['sweep_hits']} | {c['min_stub_gap_in_travel']:.2f} | {fp} | {c['head_over_lip_radial']:.2f} |")
    tight = [c for c in r["corners"] if c["roller"] == "Standard" and c["corner"].startswith("very tight")]
    if tight:
        c = tight[0]
        w(f"\nOn the 'very tight' corner the Standard stub keeps only {c['min_stub_gap_in_travel']:.2f} mm: it still "
          "assembles in CAD, but a real print that far off would feel gritty or bind. The Loose roller keeps "
          "≥ 0.35 mm on every corner. The fit coupon tells you which roller your printer needs before you print "
          "the base.\n")

    w("## 8. Print orientation: overhangs\n")
    w("| Part | Steeper than 45° (mm²) | Bridges (mm²) | Engraving ceilings on the bed face (mm²) | Exactly 45° (mm²) | Where |")
    w("|---|---:|---:|---:|---:|---|")
    for p in r["parts"].values():
        oh = p["overhang"]
        where = "; ".join(f"{g['kind']} {g['area_mm2']:.1f} mm² at z {g['z_range'][0]:.1f}-{g['z_range'][1]:.1f}" for g in oh["regions"]) or "-"
        w(f"| {p['name']} | {oh['steep_area']:.2f} | {oh['flat_area']:.2f} | {oh['engraving_ceiling_area']:.1f} | {oh['at_45_area']:.0f} | {where} |")
    w("\nThe 45° faces are the slot lips (base) and the stub-head cone (rollers), both designed at exactly 45°. "
      "The engraving ceilings are the marks cut 0.4-0.6 mm into the bed face (text on the base's back, the index "
      "line on each roller's front): the printer bridges each one across a stroke 0.5-1.2 mm wide.\n")

    m = r["models"]
    w("## 9. Hand-calculation models (predictions, not measurements)\n")
    w(f"Friction margin = available friction / {m['mu_required']:.3f}:\n")
    w("| μ (handle vs roller) | " + " | ".join(m["friction_margin_by_mu"]) + " |")
    w("|---|" + "---:|" * len(m["friction_margin_by_mu"]))
    w("| margin | " + " | ".join(f"{v:.2f}" for v in m["friction_margin_by_mu"].values()) + " |\n")
    w("| Tool weight | N per roller | Ramp force | Hertz p₀ on a steel handle, Ø19 / Ø32 (MPa) | Ramp p₀ (MPa) | Back-plate prying (MPa) | Stub pull if yanked (N) | Neck tension (MPa) | Top screw pull-out (N) |")
    w("|---|---:|---:|---|---:|---:|---:|---:|---:|")
    for row in m["load_table"]:
        hz = row["hertz_steel / aluminium handle"]
        w(f"| {row['weight_kg']:.1f} kg | {row['N_handle']:.0f} | {row['F_ramp']:.0f} | {hz[19.0]['p0']:.0f} / {hz[32.0]['p0']:.0f} | "
          f"{row['ramp_p0_MPa']:.0f} | {row['prying_bending_MPa']:.1f} | {row['yank_force_on_stub_N']:.0f} | "
          f"{row['neck_tension_MPa']:.1f} | {row['top_screw_pullout_N']:.0f} |")
    w(f"\nRoller ≈ {m['roller_mass_g_est']:.1f} g printed (estimate); gravity pulls it down the ramp with "
      f"{m['roller_gravity_along_ramp_N'] * 1000:.0f} mN, with no pivot friction to overcome. Base ≈ {m['base_mass_g_est']:.0f} g.\n")
    w("Elastic Hertz p₀ is a point-contact estimate. Local yield in the roller rim starts near p₀ ≈ 1.6 σy "
      "(≈ 80-110 MPa for printed PLA / PETG), so on a hard steel or aluminium handle a small, contained contact "
      "mark can form above about 1 kg. On wood and plastic handles p₀ stays below that up to the 2 kg rating. A "
      "mark does not change the wedge angle, so it does not change whether the grip holds: the roller just settles "
      "a fraction of a millimetre lower. The rating is 2 kg per holder; heavier tools need the physical test in "
      "PHYSICAL_TESTING.md.\n")
    with open(path, "w") as fh:
        fh.write("\n".join(L))
