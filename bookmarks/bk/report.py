"""BK-01 BOOKMARKS: the validation report (markdown), written from the measured checks."""

import datetime

from . import params as P


def _table(rows):
    if not rows:
        return ""
    keys = []
    for r in rows:
        keys += [k for k in r if k not in keys]
    out = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(k, "")) for k in keys) + " |")
    return "\n".join(out) + "\n"


def write_report(path, checks, result):
    n_ok = sum(c["ok"] for c in checks)
    L = [f"# BK-01 Bookmarks: validation report\n",
         f"Generated by `bookmarks.py` on {datetime.date.today().isoformat()}. Every value below is "
         "measured from the exported geometry (manifold3d sections and booleans, and trimesh re-reading "
         "the files from disk), not copied from the parameters.\n",
         f"**{n_ok} / {len(checks)} checks pass.**\n",
         "Status: CAD-validated. Not yet printed; see the first-print checklist in `PRINT_SETTINGS.md`.\n",
         "| # | Check | Result |", "|---|---|---|"]
    for i, c in enumerate(checks, 1):
        L.append(f"| {i} | {c['name']} | {'PASS' if c['ok'] else '**FAIL**'} |")
    L.append("")
    for i, c in enumerate(checks, 1):
        L.append(f"## {i}. {c['name']}: {'PASS' if c['ok'] else 'FAIL'}\n")
        for k, v in c.items():
            if k in ("name", "ok"):
                continue
            if k == "rows" and isinstance(v, list) and v and isinstance(v[0], dict):
                L.append(_table(v))
            elif k == "stations":
                L.append("| height z (mm) | cavity width (mm) | cavity depth (mm) | area (mm2) |\n|---|---|---|---|")
                for z, s in v.items():
                    L.append(f"| {z} | {s['width']} | {s['depth']} | {s['area']} |")
                L.append("")
            elif k == "plans":
                L.append("| plan | filaments | layers with 2+ colours | most colours in a layer | "
                         "changes on a 1-nozzle printer | flushes on the 2-nozzle H2C | nozzle map (filament slots) |")
                L.append("|---|---|---|---|---|---|---|")
                for pn, s in v.items():
                    nm = ", ".join(f"{side}: {list(ss)}" for side, ss in s["nozzle_map"].items())
                    L.append(f"| {pn} | {s['filaments']} | {s['layers_with_2plus']} | {s['max_in_one_layer']} | "
                             f"{s['changes_one_nozzle']} | {s['flushes_two_nozzles']} | {nm} |")
                L.append("")
            else:
                L.append(f"- **{k}**: {v}")
        L.append("")
    open(path, "w").write("\n".join(L))
