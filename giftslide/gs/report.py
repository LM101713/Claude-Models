"""Validation report (markdown + json) from a Checks object."""

import datetime
import json

from . import estimate as Est
from .params import P


def _f(x, n=2):
    return f"{x:.{n}f}"


def write(C, md_path, json_path, p=P, files=None):
    rows = C.rows
    n_ok = sum(r["ok"] for r in rows)
    L = []
    L.append("# GS-05 GIFT SLIDE: CAD validation report\n")
    L.append(f"Generated by `giftslide.py` on {datetime.date.today().isoformat()}. "
             f"**{n_ok} of {len(rows)} checks pass.**\n")
    L.append("> These are geometry and hand-calculation checks on the CAD model. Nothing here has been "
             "printed or physically tested. Forces come from a beam model with an assumed modulus and "
             "friction; their spread across material values is shown below. See `TEST_PLAN.md` for "
             "what a real print has to prove.\n")
    groups = []
    for r in rows:
        if r["group"] not in groups:
            groups.append(r["group"])
    for g in groups:
        L.append(f"\n## {g}\n")
        L.append("| | Check | Value | Limit |")
        L.append("|---|---|---|---|")
        for r in rows:
            if r["group"] == g:
                note = f"<br><sub>{r['note']}</sub>" if r["note"] else ""
                L.append(f"| {'PASS' if r['ok'] else '**FAIL**'} | {r['name']}{note} | {r['value']} | {r['limit']} |")

    b = C.data["beam"]
    L.append("\n## Detent model inputs\n")
    L.append(f"- Flexure beam: fixed-fixed, {b['L']:.0f} mm long, section area {b['A']:.2f} mm², "
             f"I = {b['I']:.3f} mm⁴ (bending across the lid), extreme fibre {b['c']:.2f} mm")
    L.append(f"- E = {p.E_mpa:.0f} MPa (printed PLA along the beads), μ = {p.mu} (PLA on PLA)")
    L.append(f"- Stiffness k = {b['k']:.2f} N/mm per side; strain = {b['strain_per_mm'] * 100:.2f} % per mm of deflection")
    L.append(f"- Bump {p.bump_p} mm proud of the land, flanks {p.bump_front_deg:.0f}° (front) / {p.bump_rear_deg:.0f}° (rear); "
             f"relief track {p.relief_d} mm deep; flanks: R1 {p.r1_open_deg:.0f}° opening / {p.r1_close_deg:.0f}° closing, "
             f"open stop {p.stop_deg:.0f}°")
    L.append("\n## Detent forces across printer variation\n")
    L.append("Offsets are per side: tray + means its groove prints wider, lid + means the lid prints wider.\n")
    L.append("| Corner | Lateral clearance | Beam deflection | Opening click | Closing click | Open stop | Fit lid | Drag in travel | Max strain |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for k, r in C.data["detent"].items():
        L.append(f"| {k} | {_f(r['clear'])} mm | {_f(r['d_r1'])} mm | {_f(r['F_open_r1'], 1)} N | "
                 f"{_f(r['F_close_r1'], 1)} N | {_f(r['F_stop'], 1)} N | {_f(r['F_insert'], 1)} N | "
                 f"{_f(r['F_run'])} N | {_f(r['strain_max'] * 100)} % |")
    L.append("\nThe Standard lid alone at the two extreme corners (why the Loose and Snug lids exist):\n")
    L.append("| Corner | Clearance | Opening click | Open stop | Drag |")
    L.append("|---|---|---|---|---|")
    for k, r in C.data["unfixed_extremes"].items():
        L.append(f"| {k} | {_f(r['clear'])} mm | {_f(r['F_open_r1'], 1)} N | {_f(r['F_stop'], 1)} N | {_f(r['F_run'])} N |")
    L.append("\nNominal geometry, material spread:\n")
    L.append("| E (MPa) | μ | Opening click | Closing click | Open stop |")
    L.append("|---|---|---|---|---|")
    for (E, mu), r in C.data["spread"].items():
        L.append(f"| {E} | {mu} | {_f(r['F_open_r1'], 1)} N | {_f(r['F_close_r1'], 1)} N | {_f(r['F_stop'], 1)} N |")

    L.append("\n## 3-D cross-check of the detent model\n")
    L.append("Beam deflection the real solids demand (bisection on booleans: the smallest inward shift of the "
             "bump that clears the tray) against the 1-D model.\n")
    L.append("| Lid travel | 3-D | 1-D model |")
    L.append("|---|---|---|")
    for s, d3, d1 in C.data["bump_crosscheck"]:
        L.append(f"| {s:.1f} mm | {d3:.3f} mm | {d1:.3f} mm |")

    L.append("\n## Print estimate\n")
    pr = Est.PROCESS
    L.append(f"Estimated by slicing the solids layer by layer with the assumptions of `{pr['process']}` on a "
             f"{pr['printer']}: {pr['wall_loops']} walls, {pr['top_layers']} top / {pr['bottom_layers']} bottom layers, "
             f"{int(pr['infill'] * 100)} % {pr['infill_pattern']} infill, trapezoidal acceleration. "
             "No slicer was available in the build environment; expect ±20 % against Bambu Studio.\n")
    L.append("| Part | Layers | Print time | Filament | Solid volume |")
    L.append("|---|---|---|---|---|")
    for k, e in C.data["estimate"].items():
        L.append(f"| {k} | {e['layers']} | {e['print_min']:.0f} min | {e['grams']:.1f} g ({e['metres']:.2f} m) | {e['solid_cm3']:.1f} cm³ |")
    L.append(f"\nAdd about {pr['start_overhead_min']:.0f} min per plate for heating, wiping and the prime line.")

    L.append("\n## Overhang survey (downward faces steeper than 41° that are not on the bed)\n")
    for k in [k for k in C.data if k.startswith("overhang_")]:
        regs = C.data[k]
        txt = ", ".join(f"z {z:.2f} mm: {a:.1f} mm² at most {w:.2f} mm wide" for z, a, w in regs) or "none"
        L.append(f"- **{k[9:]}**: {txt}")
    if files:
        L.append("\n## Exported files (re-read from disk)\n")
        L.append("| File | Triangles | Volume | Check |")
        L.append("|---|---|---|---|")
        for f in files:
            L.append(f"| `{f['file']}` | {f['tris']} | {f['vol'] / 1000:.2f} cm³ | {'PASS' if f['ok'] else '**FAIL**'} |")
    open(md_path, "w").write("\n".join(L) + "\n")

    def clean(o):
        if isinstance(o, dict):
            return {str(k): clean(v) for k, v in o.items() if k != "curves"}
        if isinstance(o, (list, tuple)):
            return [clean(v) for v in o]
        if hasattr(o, "item"):
            return o.item()
        if isinstance(o, (int, float, str, bool)) or o is None:
            return o
        return str(o)

    data = {k: v for k, v in C.data.items() if k != "parts"}
    json.dump(dict(passed=C.passed, n_ok=n_ok, n=len(rows), checks=rows, data=clean(data), files=files or []),
              open(json_path, "w"), indent=1)
