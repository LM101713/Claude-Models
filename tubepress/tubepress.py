"""
ODD LAYER TP-01 TUBEPRESS: a two-part ratchet toothpaste squeezer that loads from the side.

    python tubepress.py            build, export STL + 3MF, run every check, write the reports
    python tubepress.py --render   ...plus the renders (Blender as a Python module, Cycles CPU)
"""

import argparse
import datetime
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from tp import export as X  # noqa: E402
from tp import geom as G  # noqa: E402
from tp import printest as E  # noqa: E402
from tp import validate as V  # noqa: E402
from tp.params import NIP_VARIANTS, P  # noqa: E402

M = os.path.join(HERE, "models")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--render", action="store_true")
    a = ap.parse_args()
    os.makedirs(os.path.join(M, "stl"), exist_ok=True)
    os.makedirs(os.path.join(M, "3mf"), exist_ok=True)

    frame = G.frame()
    key = G.key()
    keyp = V.key_print(key)
    stls = {
        "TP-01 Frame": os.path.join(M, "stl", "TP01_A_Frame_Standard.stl"),
        "TP-01 Key": os.path.join(M, "stl", "TP01_B_Key.stl"),
    }
    X.write_stl(stls["TP-01 Frame"], frame, "TP-01 Frame Standard")
    X.write_stl(stls["TP-01 Key"], keyp, "TP-01 Key")
    variants = {}
    for name, nip in NIP_VARIANTS.items():
        if name == "Standard":
            continue
        f = G.frame(nip=nip)
        variants[name] = f
        X.write_stl(os.path.join(M, "stl", f"TP01_A_Frame_{name}_nip{nip:.1f}_alt.stl"), f, f"TP-01 Frame {name}")
    layout = V.plate_layout(frame, keyp)
    mf = os.path.join(M, "3mf", "TP01_set_A1mini_plate.3mf")
    X.write_3mf(mf, layout, plate_center=(90.0, 90.0))

    parts_print = {"TP-01 Frame": frame, "TP-01 Key": keyp}
    est = {n: E.estimate(m, E.PETG) for n, m in parts_print.items()}
    est_pla = {n: E.estimate(m, E.PLA) for n, m in parts_print.items()}
    rat = V.check_ratchet()
    checks = [
        V.check_build_volume(layout),
        V.check_manifold(list(parts_print.items()) + [(f"Frame {n} (alt)", f) for n, f in variants.items()]),
        V.check_files(parts_print, stls, mf),
        V.check_overhangs(list(parts_print.items())),
        V.check_thin(list(parts_print.items())),
        V.check_assembled(frame, key),
        V.check_insertion(frame, key),
        rat,
        V.check_leaf(rat[2]["pawl_drop_free_direction_mm"]),
        V.check_tubes(),
        V.check_budget(est_pla),
        V.check_budget(est),
    ]
    checks[-2] = (checks[-2][0] + " - PLA", checks[-2][1], checks[-2][2])
    checks[-1] = (checks[-1][0] + " - PETG", checks[-1][1], checks[-1][2])
    n_ok = sum(1 for c in checks if c[1])
    print(f"\nTP-01 TUBEPRESS: {n_ok}/{len(checks)} checks pass\n")
    for n, ok, _ in checks:
        print(("PASS " if ok else "FAIL ") + n)
    with open(os.path.join(M, "TP01_validation.json"), "w") as f:
        json.dump(dict(checks=[dict(name=n, passed=ok, detail=d) for n, ok, d in checks]), f, indent=1, default=str)
    write_report(os.path.join(M, "TP01_validation_report.md"), checks, est_pla, est, frame, keyp)
    from tp import report as R
    R.drawing(os.path.join(HERE, "docs", "TP01_drawing.png"), frame, key)
    R.ratchet_diagram(os.path.join(HERE, "docs", "TP01_ratchet.png"))
    if a.render:
        from tp import scene
        scene.render_all(frame, key, keyp, os.path.join(HERE, "renders"), os.path.join(M, "TP01_TubePress.blend"))
    return 0 if n_ok == len(checks) else 1


def write_report(path, checks, est_pla, est, frame, keyp):
    L = ["# TP-01 TUBEPRESS: validation report\n",
         f"_Generated by `tubepress.py` on {datetime.date.today().isoformat()}. CAD checks only: nothing here has "
         "been printed or physically tested._\n",
         f"**{sum(1 for c in checks if c[1])} / {len(checks)} checks pass.**\n", "| # | Check | Result |", "|---|---|---|"]
    for i, (n, ok, _) in enumerate(checks, 1):
        L.append(f"| {i} | {n} | {'PASS' if ok else '**FAIL**'} |")
    L.append("\n## Print estimate (slice-based estimator, not a slicer: confirm in Bambu Studio)\n")
    L.append("| Part | PLA g | PLA min | PETG g | PETG min |\n|---|---|---|---|---|")
    for n in est:
        L.append(f"| {n} | {est_pla[n]['grams']:.1f} | {est_pla[n]['minutes']:.0f} | {est[n]['grams']:.1f} | {est[n]['minutes']:.0f} |")
    L.append(f"| **Set** | **{sum(e['grams'] for e in est_pla.values()):.1f}** | **{sum(e['minutes'] for e in est_pla.values()):.0f}** | "
             f"**{sum(e['grams'] for e in est.values()):.1f}** | **{sum(e['minutes'] for e in est.values()):.0f}** |")
    L.append("\nAssumptions: A1 mini, 0.4 mm nozzle, 0.20 mm layers, 2 walls, 5 top / 3 bottom, 15 % infill; Bambu "
             "standard speeds capped by volumetric flow (PLA 21, PETG 13 mm3/s). Ranges: grams -8/+10 %, time -20/+25 %. "
             "Printed one after the other on one plate, the real time is less than the sum (shared heat-up and layers).\n")
    L.append("## Details\n")
    for i, (n, ok, d) in enumerate(checks, 1):
        L.append(f"### {i}. {n}: {'PASS' if ok else 'FAIL'}\n\n```\n{json.dumps(d, indent=1, default=str)}\n```\n")
    with open(path, "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
