def drainage_map(path, m, maps):
    xs, ys, Z, fate = maps
    fig, ax = plt.subplots(1, 1, figsize=(11, 6.6), dpi=150)
    Zm = np.ma.masked_invalid(Z)
    wet = np.isfinite(Z) & (Z < 12)
    zw = np.ma.masked_where(~wet, Z)
    ax.imshow(np.ma.masked_where(wet, Zm).T, origin="lower", extent=[xs[0], xs[-1], ys[0], ys[-1]],
              cmap=ListedColormap(["#C9C6C0"]), aspect="equal")
    im = ax.imshow(zw.T, origin="lower", extent=[xs[0], xs[-1], ys[0], ys[-1]], cmap="Blues_r", aspect="equal",
                   vmin=np.nanmin(Z), vmax=8)
    # flow arrows: local downhill gradient on a coarse grid
    gy, gx = np.gradient(np.where(wet, Z, np.nan).T, ys[1] - ys[0], xs[1] - xs[0])
    step = 8
    Xg, Yg = np.meshgrid(xs, ys)
    sel = (slice(None, None, step), slice(None, None, step))
    u, v = -gx[sel], -gy[sel]
    n = np.hypot(u, v)
    ok = np.isfinite(n) & (n > 1e-4)
    ax.quiver(Xg[sel][ok], Yg[sel][ok], (u / n)[ok], (v / n)[ok], color=ORANGE, scale=55, width=0.0022, headwidth=4)
    bad = (fate == 2) | (fate == 3)
    if bad.any():
        bi = np.argwhere(bad)
        ax.scatter(xs[bi[:, 0]], ys[bi[:, 1]], s=4, c="red", label="puddle / counter")
    ax.axhline(0, color=INK, lw=0.8, ls="--")
    ax.text(W + 3, 1.5, "y = 0: counter edge\n(spouts overhang\nthe sink)", fontsize=8, color=INK, va="bottom")
    for b in BAYS:
        ax.text(b["xc"], P.D + 3, b["name"], ha="center", fontsize=8, color=INK)
    cb = fig.colorbar(im, ax=ax, shrink=0.7)
    cb.set_label("floor height (mm)")
    n_wet = int(wet.sum())
    n_sink = int((fate == 1).sum())
    ax.set_title(f"SD-01 drainage: steepest-descent routing on the ray-cast top surface, 0.5 mm grid\n"
                 f"{n_sink} of {n_wet} wet cells run off the spouts into the sink "
                 f"({100*n_sink/max(n_wet,1):.2f} %); arrows = downhill direction", fontsize=10)
    ax.set_xlabel("x (mm)")
    ax.set_ylabel("y (mm), sink side at the bottom")
    ax.set_xlim(xs[0], xs[-1] + 40)
    ax.set_ylim(ys[0], P.D + 8)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


