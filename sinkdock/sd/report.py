def _fmt(v):
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def write_report(path, m, checks, est_pla, est_petg):
    bb = m.bounding_box()
    L = []
    L.append("# SD-01 SINKDOCK: validation report\n")
    L.append(f"_Generated by `sinkdock.py` on {datetime.date.today().isoformat()}. CAD checks only: nothing here "
             "has been printed or physically tested._\n")
    n_ok = sum(1 for c in checks if c[1])
    L.append(f"**{n_ok} / {len(checks)} checks pass.**\n")
    L.append("| # | Check | Result |\n|---|---|---|")
    for i, (name, ok, _) in enumerate(checks, 1):
        L.append(f"| {i} | {name} | {'PASS' if ok else '**FAIL**'} |")
    L.append("")
    L.append("## Part\n")
    L.append(f"- Overall size: **{bb[3]-bb[0]:.1f} x {bb[4]-bb[1]:.1f} x {bb[5]-bb[2]:.1f} mm** (W x D x H, spouts included)")
    L.append(f"- Solid-model volume: {m.volume()/1000:.1f} cm3, {m.num_tri()} triangles, genus {m.genus()}")
    L.append("- Bays, left to right: " + ", ".join(f"{b['name']} {b['w']:.1f} mm" for b in BAYS))
    L.append(f"- Walls: dividers {P.wall_inner} mm, outer walls {P.wall_outer} mm, cup {P.cup_t} mm")
    L.append(f"- Floor: {P.slope_y} deg fall to the front, {P.slope_x} deg V cross-fall to a centre gutter in every bay; "
             f"{P.z0} mm thick at the gutter mouths")
    L.append("")
    L.append("## Print estimate\n")
    L.append("From `sd/printest.py`, a layer-by-layer estimator that stands in for a slicer, which could not be "
             "installed here. Assumptions: Bambu A1 mini, 0.4 mm nozzle, 0.20 mm layers, 2 walls, 5 top / 3 bottom "
             "layers, 15 % sparse infill. Speeds are Bambu's standard process, capped by the filament's maximum "
             "volumetric flow (PLA 21, PETG 13 mm3/s) and derated for acceleration. **Confirm in the slicer before quoting.**\n")
    L.append("| Filament | Grams (range) | Time (range) |\n|---|---|---|")
    for e in (est_pla, est_petg):
        L.append(f"| {e['filament']} | {e['grams']:.1f} g ({e['grams_range'][0]:.0f}-{e['grams_range'][1]:.0f}) | "
                 f"{e['minutes']:.0f} min ({e['minutes_range'][0]:.0f}-{e['minutes_range'][1]:.0f}) |")
    L.append("")
    L.append("## Details\n")
    for i, (name, ok, d) in enumerate(checks, 1):
        L.append(f"### {i}. {name}: {'PASS' if ok else 'FAIL'}\n")
        L.append("```")
        L.append(_dump(d))
        L.append("```\n")
    with open(path, "w") as f:
        f.write("\n".join(L))


def _dump(d, ind=0):
    out = []
    pad = "  " * ind
    if isinstance(d, dict):
        for k, v in d.items():
            if isinstance(v, (dict, list)) and v and isinstance(v, dict):
                out.append(f"{pad}{k}:")
                out.append(_dump(v, ind + 1))
            elif isinstance(v, list) and v and isinstance(v[0], dict):
                out.append(f"{pad}{k}:")
                for it in v:
                    out.append(f"{pad}  - " + ", ".join(f"{a}={_fmt(b)}" for a, b in it.items()))
            else:
                out.append(f"{pad}{k}: {_fmt(v)}")
    else:
        out.append(pad + _fmt(d))
    return "\n".join(out)


