"""
ORBIT architecture numbers: positions, clearances, loads and spring estimates.

Hand calculations from the layout parameters, written out so they can be checked and
re-run. Every strength figure is an estimate from handbook-style material values, not a
measurement; none of it replaces the physical tests.

    python -m uc.arch            # prints the tables and writes docs/arch_numbers.md
"""

import math
import os

from . import geom as G
from . import orbit2 as O

PETG = dict(E=2000.0, yield_=45.0, inter=20.0, mu=0.30, rho=1.27e-3)   # MPa, MPa, MPa (across layers), -, g/mm3
PLA = dict(E=3200.0, yield_=55.0, inter=25.0, mu=0.30, rho=1.24e-3)
LOST = 2.5            # rack free travel either side of centre (mm)
LIFT = 2.2            # pawl lift (mm)
ENGAGE = 2.0          # tooth depth in the window (mm)
TOOTH = (2.4, 3.0)    # each of the two pawl teeth: x, z (mm); they share a 6.2 mm window
CUT_LOAD = (100.0, 200.0)   # assumed hard cut / abuse (N)
PULL = 30.0           # assumed pull-out drag (N)
CIRC = 60.0           # rack travel per wheel turn with a 12-tooth, module 1.5915 pinion


def positions():
    rows = []
    nose = lambda z: O.MOUTH + O.RK(z)
    for k in range(0, O.TIPS + 1):
        s = 0.0 if k == 0 else O.PARK + G.SEG * (k - 1)
        length = G.BLADE_L - G.SEG * max(k - 1, 0)
        tip = O.TIP + O.PARK if k == 0 else O.TIP
        tail = tip + length
        rows.append(dict(
            name="parked" if k == 0 else f"tip {k}", travel=s, tip_x=tip, exposed=max(0.0, O.MOUTH - tip),
            blade_len=length, plate_front=tail - 12.5, plate_margin=tail - 12.5 - O.CH_X0, pawl_x=tail + 14.0,
            block_rear=tail + 24.5, wheel_deg=(s / CIRC * 360.0) % 360.0,
            rack_front_gap=(O.RACK_F0 + (O.PARK - s)) - (O.MOUTH + 2.5) if True else 0))
    return rows


def spring_arm(mat, L, t, b, lift=LIFT):
    I = b * t ** 3 / 12
    F = 3 * mat["E"] * I * lift / L ** 3
    strain = 1.5 * t * lift / L ** 2
    return F, strain * 100, strain * mat["E"]


def report():
    out = []
    P = out.append
    P("# ORBIT architecture numbers\n")
    P("Generated by `python -m uc.arch`. Estimates only: handbook material values, no test data.\n")

    P("## Blade positions (blade assumed 100 x 18 x 0.5 mm, 10 mm segments)\n")
    P("| Position | Travel | Tip exposed | Blade left | Carriage plate to channel start | Pawl x | Wheel angle |")
    P("|---|---|---|---|---|---|---|")
    for r in positions():
        P(f"| {r['name']} | {r['travel']:.1f} | {r['exposed']:.1f} | {r['blade_len']:.0f} | {r['plate_margin']:.1f} | "
          f"{r['pawl_x']:.1f} | {r['wheel_deg']:.0f}° |")
    slit_edge = O.CH_X0 - O.MOUTH
    slit_back = O.CH_X0 - (O.MOUTH + O.RK(G.BLADE_H))
    P(f"\n- Parked tip sits {O.TIP + O.PARK - O.MOUTH:.1f} mm inside the mouth.")
    P(f"- Blade guided in the nose slit: {slit_edge:.1f} mm at the cutting edge, {slit_back:.1f} mm at the back edge.")
    P(f"- Exposed length is {G.SEG:.0f} mm at every working position, so support ratio at the edge is "
      f"{slit_edge / G.SEG:.1f}:1 and at the back {slit_back / G.SEG:.2f}:1 without channel lips.")
    P(f"- Stub left after tip {O.TIPS}: {G.BLADE_L - G.SEG * O.TIPS:.0f} mm.")
    tot = O.PARK + G.SEG * (O.TIPS - 1)
    P(f"- Total travel {tot:.1f} mm = {tot / CIRC:.2f} wheel turns.\n")

    P("## Lock teeth and window (two opposed pawls; each carries its own direction alone)\n")
    P("| Load | Tooth bearing on window | Tooth shear | Blade tail on shoulder |")
    P("|---|---|---|---|")
    for F in CUT_LOAD:
        P(f"| {F:.0f} N | {F / (TOOTH[1] * ENGAGE):.1f} MPa | {F / (TOOTH[0] * TOOTH[1]):.1f} MPa | {F / (G.BLADE_H * G.BLADE_T):.1f} MPa |")
    P(f"\nPETG reference: yield about {PETG['yield_']:.0f} MPa in the layer plane, about {PETG['inter']:.0f} MPa across layers.")
    lig = G.SEG - 2.9
    P(f"Wall between working windows: {lig:.1f} mm long x 2.5 mm thick.\n")

    P("## Blade lug (pull-out only)\n")
    d = 3.9
    P(f"At {PULL:.0f} N: bearing on the blade edge {PULL / (d * G.BLADE_T):.0f} MPa, lug shear "
      f"{PULL / (math.pi * d * d / 4):.1f} MPa. Bearing is the limit: a 0.5 mm steel edge on plastic.\n")

    P("## Pawl spring arm (in-plane cantilever, deflected only while the wheel is being turned)\n")
    P("| Material | Length | Thickness | Force at full lift | Peak strain | Peak stress |")
    P("|---|---|---|---|---|---|")
    for name, mat in (("PETG", PETG), ("PLA", PLA)):
        for (L, t) in ((18, 1.2), (20, 1.3), (22, 1.4)):
            F, e, sg = spring_arm(mat, L, t, TOOTH[1])   # one arm, 3 mm tall
            P(f"| {name} | {L} | {t} | {F:.1f} N | {e:.2f}% | {sg:.0f} MPa |")
    P("\nTarget: peak strain at or below 1% for a part flexed thousands of times. To be confirmed by cycling.\n")

    P("## Return budget for the forward-blocking pawl (the only one that needs the rack to re-centre)\n")
    Fs, _, _ = spring_arm(PETG, 22, 1.4, TOOTH[1])
    cam = math.atan2(LIFT, LOST)
    F_cam = Fs * math.tan(cam)
    F_det = 3.0
    P(f"- Spring arm at full lift: {Fs:.1f} N. Through a {math.degrees(cam):.0f}° cam that is about {F_cam:.1f} N on the rack "
      "(falling to zero as the tooth seats).")
    P(f"- Rack detent (finger on the shuttle, relaxed when seated): design value {F_det:.0f} N of centring force.")
    P(f"- Available to re-centre the rack: about {F_cam + F_det:.1f} N at the start of the return, {F_det:.0f} N at the end.")
    P(f"- Drag allowed at the rack with a factor of two in hand: about {(F_det) / 2:.1f} N at the end of the return. "
      f"That is {(F_det) / 2 * (O.M * O.Z / 2) / O.WR:.2f} N at the wheel rim.")
    P("- This is why the wheel must turn freely and why the detent acts on the rack, not on the wheel.\n")

    P("## Shock\n")
    m_rack = 3.6e3 * PETG["rho"] / 1000 * 1.0      # ~3.6 cm3 -> kg*1e-3 handled below
    m_rack_g = 3.6 * 1.27
    m_wheel_g = 12.1 * 1.27
    I = 0.5 * (m_wheel_g / 1000) * (0.0165) ** 2
    m_refl_g = I / (0.00955 ** 2) * 1000
    a_thr = F_det / (m_rack_g / 1000)
    P(f"- Rack about {m_rack_g:.1f} g; wheel about {m_wheel_g:.0f} g, which the rack feels as about {m_refl_g:.0f} g.")
    P(f"- The detent holds the rack up to about {a_thr / 9.81:.0f} g of deceleration along the tool. A drop onto a hard "
      "floor is typically several hundred g or more.")
    P("- So a drop on the nose or tail can shift the rack and lift the pawl when the carry bolt is not engaged. "
      "With the carry bolt engaged the rack cannot move.\n")

    P("## Carry bolt and tail cap\n")
    Fr = 60.0
    P(f"- Wheel forced against the bolt: about {Fr:.0f} N at the rack from a hard thumb push. Bolt shear (two planes) "
      f"{Fr / (2 * math.pi * O.BOLT_R ** 2):.1f} MPa; bearing in the rack notch {Fr / (2 * O.BOLT_R * 6.8):.1f} MPa.")
    P(f"- If the pawl has failed and only the bolt holds: the carriage can still move {LOST:.1f} mm plus backlash. "
      f"Parked tip stays {O.TIP + O.PARK - O.MOUTH - LOST - 0.3:.1f} mm inside the mouth.")
    rail = 2 * 4.0 * 18.0
    for F in CUT_LOAD:
        P(f"- Tail rails at {F:.0f} N along the tool: {F / rail:.1f} MPa on two 4 x 18 mm necks, in the layer plane.")
    txt = "\n".join(out) + "\n"
    return txt


if __name__ == "__main__":
    t = report()
    print(t)
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(here, "docs", "arch_numbers.md"), "w") as f:
        f.write(t)
